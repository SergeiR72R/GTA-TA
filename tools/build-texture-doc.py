#!/usr/bin/env python3
"""Собирает задание для Claude в Chrome — CLAUDE_CHROME_TEXTURES.md — из tools/texlist.py.

    python3 tools/build-texture-doc.py            # все текстуры
    python3 tools/build-texture-doc.py --missing  # только те, которых ещё нет в assets/textures/src
"""
import os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from texlist import TEXTURES

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
SRC = os.path.join(ROOT, 'assets', 'textures', 'src')
OUT = os.path.join(ROOT, 'CLAUDE_CHROME_TEXTURES.md')
have = {os.path.splitext(f)[0] for f in os.listdir(SRC)} if os.path.isdir(SRC) else set()
only_missing = '--missing' in sys.argv
items = [t for t in TEXTURES if not (only_missing and t['name'] in have)]
first = next((t for t in items if t['kind'] == 'seamless'), items[0])

KIND = {
    'seamless': 'бесшовная: левый край продолжает правый, верхний — нижний; без предмета в центре',
    'front': 'вид строго спереди, как чертёж; предмет на весь кадр, без фона и перспективы',
    'alpha': 'предмет на сплошном пурпурном фоне #FF00FF (фон игра вырежет сама)',
}

L = []
w = L.append
w('# Задание для Claude в Chrome: все текстуры игры «ХАМСИН 3D — Тель-Авив»')
w('')
w('> Откройте этот файл в боковой панели **Claude в Chrome** и скажите:')
w('> «Выполни задание из этого файла».')
w('> Здесь все текстуры 3D-квартала: штукатурка и камень домов, окна, витрины лавок,')
w('> асфальт и тротуары, деревья, детали машин. Пока картинки нет, игра рисует похожую')
w('> текстуру сама, так что картинки можно добавлять частями.')
w('')
w(f'Всего: **{len(items)}** картинок' + (' (только недостающие)' if only_missing else '') + '.')
w('')
w('## Сначала — одна картинка на согласование')
w('')
w(f'1. Сгенерируй **только № {first["n"]}** (`{first["name"]}.png`).')
w('2. Покажи её пользователю и спроси: «Так подходит? Продолжать?»')
w('3. **Дальше не иди, пока пользователь не ответит «да».** Если он просит поправить —')
w('   допиши его уточнение в конец промпта, сгенерируй заново и снова спроси. Потом добавляй')
w('   это же уточнение к похожим пунктам списка.')
w('4. После «да» — весь список по порядку.')
w('')
w('## Главное правило: имя файла')
w('')
w('Каждую скачанную картинку **назови по номеру и имени из заголовка пункта**, например')
w('`1_pl_white.png`. Если браузер не даёт переименовать — запиши в отчёт, какой скачанный')
w('файл какому номеру соответствует. Лишние варианты не скачивай.')
w('')
w('## Как работать в Google Flow (или Gemini)')
w('')
w('1. Открой https://labs.google/fx/tools/flow. Если нужен вход в аккаунт Google — попроси')
w('   пользователя войти и продолжай после этого. (Если Flow недоступен — https://gemini.google.com.)')
w('2. Создай проект «ХАМСИН 3D текстуры» и переключись на **генерацию изображений**,')
w('   1 результат на запрос, формат — как указано у пункта.')
w('3. Вставь промпт из блока кода **целиком** и запусти.')
w('4. Проверь по чек-листу. Не подходит — сгенерируй ещё раз или допиши уточнение в конец')
w('   (например, «strictly orthographic, flat, seamless edges»).')
w('5. Скачай удачную картинку в полном размере, **PNG или JPG** (не WebP), и переходи к следующей.')
w('')
w('### Чек-лист')
w('')
w('- **Бесшовные** текстуры (большинство): узор продолжается через края, нет рамки, нет')
w('  предмета в центре, нет виньетки и пятна света, нет перспективы — плоская поверхность.')
w('- **Окна, витрины, щиты, детали машин**: строго спереди, предмет заполняет весь кадр до краёв.')
w('- **Вырезки** (листья, пальма): предмет на сплошном пурпурном фоне `#FF00FF` без теней.')
w('- Нигде нет водяных знаков и логотипов. Буквы — только там, где промпт их просит')
w('  (вывески лавок на иврите, шашка такси, номер машины).')
w('')
w('### Отчёт в конце')
w('')
w('Напиши пользователю, какие номера готовы, какие пропущены и (если не получилось')
w('переименовать) какой файл к какому номеру. Файлы пусть загрузит в **новую** папку')
w('Google Диска (например, «ХАМСИН 3D — текстуры») — Claude Code сам разложит их по местам:')
w('`python3 tools/pack-textures.py <папка с картинками>`.')
w('')
w('---')
w('')
groups = []
for t in items:
    if t['group'] not in groups:
        groups.append(t['group'])
for g in groups:
    w(f'## {g}')
    w('')
    for t in [x for x in items if x['group'] == g]:
        status = 'есть (взята из GTA-original-2027 — можно сгенерировать заново в едином стиле)' if t['name'] in have else 'нет'
        w(f'### {t["n"]}. `{t["name"]}.png` — {t["title"]}')
        w('')
        w(f'- [ ] Формат {t["aspect"]}; {KIND[t["kind"]]}. Сейчас в игре: {status}.')
        w('')
        w('```')
        w(t['prompt'])
        w('```')
        w('')
open(OUT, 'w').write('\n'.join(L))
print(f'{OUT}: {len(items)} текстур')
